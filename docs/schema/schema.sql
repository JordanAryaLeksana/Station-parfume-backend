-- ---------------------------------------------------------------------
-- 9. PAYMENT — Xendit Payment Sessions (lihat docs/audit-and-roadmap.md §9)
-- ---------------------------------------------------------------------
CREATE TABLE payments (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                    BIGINT       NOT NULL REFERENCES orders (id) ON DELETE RESTRICT,
    provider                    VARCHAR(20)  NOT NULL DEFAULT 'xendit',
    reference_id                UUID         NOT NULL,      -- dikirim ke Xendit sebagai reference_id
    provider_session_id         VARCHAR(100),               -- payment_session_id ("ps-...")
    provider_payment_request_id VARCHAR(100),               -- payment_request_id
    provider_payment_id         VARCHAR(100),               -- payment_id (kunci dedup webhook)
    checkout_url                TEXT,                       -- payment_link_url
    payment_method              VARCHAR(50),                -- QRIS, VIRTUAL_ACCOUNT, EWALLET, ...
    payment_channel             VARCHAR(50),                -- BCA, OVO, DANA, ...
    amount                      BIGINT       NOT NULL,
    currency                    CHAR(3)      NOT NULL DEFAULT 'IDR',
    status                      VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    failure_reason              TEXT,
    expires_at                  TIMESTAMPTZ,
    paid_at                     TIMESTAMPTZ,
    provider_response           JSONB,                      -- respons create session terakhir
    created_at                  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at                  TIMESTAMPTZ,
    CONSTRAINT payments_provider_chk CHECK (provider IN ('xendit', 'midtrans')),
    CONSTRAINT payments_status_chk   CHECK (status IN ('PENDING', 'PAID', 'EXPIRED', 'CANCELLED', 'FAILED', 'REFUNDED')),
    CONSTRAINT payments_amount_chk   CHECK (amount > 0),
    CONSTRAINT payments_currency_chk CHECK (currency = 'IDR'),
    CONSTRAINT payments_paid_at_chk  CHECK (status NOT IN ('PAID', 'REFUNDED') OR paid_at IS NOT NULL)
);
CREATE UNIQUE INDEX payments_reference_uq        ON payments (reference_id);
CREATE UNIQUE INDEX payments_provider_session_uq ON payments (provider, provider_session_id) WHERE provider_session_id IS NOT NULL;
CREATE UNIQUE INDEX payments_provider_payment_uq ON payments (provider, provider_payment_id) WHERE provider_payment_id IS NOT NULL;
-- Maks 1 percobaan PENDING dan maks 1 PAID per order.
CREATE UNIQUE INDEX payments_one_pending_uq      ON payments (order_id) WHERE status = 'PENDING' AND deleted_at IS NULL;
CREATE UNIQUE INDEX payments_one_paid_uq         ON payments (order_id) WHERE status = 'PAID'    AND deleted_at IS NULL;
CREATE INDEX        payments_order_idx           ON payments (order_id);
-- Untuk job rekonsiliasi: cari PENDING yang sudah lewat expires_at.
CREATE INDEX        payments_pending_expiry_idx  ON payments (expires_at) WHERE status = 'PENDING';

-- Log webhook mentah, append-only (tanpa soft delete). Dedup via unique key.
CREATE TABLE payment_events (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider            VARCHAR(20)  NOT NULL,
    event_type          VARCHAR(100) NOT NULL,          -- payment_session.completed, ...
    provider_payment_id VARCHAR(100) NOT NULL,
    payment_id          BIGINT       REFERENCES payments (id) ON DELETE SET NULL,
    payload             JSONB        NOT NULL,
    received_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    processed_at        TIMESTAMPTZ,
    process_error       TEXT,
    CONSTRAINT payment_events_dedup_uq UNIQUE (provider, event_type, provider_payment_id)
);
CREATE INDEX payment_events_payment_idx     ON payment_events (payment_id);
CREATE INDEX payment_events_unprocessed_idx ON payment_events (received_at) WHERE processed_at IS NULL;


