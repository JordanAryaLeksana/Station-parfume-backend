-- =====================================================================
-- Station Parfume — Schema v2 (Shopee-aligned)
-- PostgreSQL 13+  ·  semua harga BIGINT dalam rupiah (tanpa desimal)
--
-- Ini schema LENGKAP untuk database baru (fresh install).
-- Untuk DB yang sudah ada isinya, jadikan file ini migrasi goose
-- (lihat docs/schema/README.md §7) — JANGAN jalankan lewat AutoMigrate.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. USERS & ALAMAT
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    phone         VARCHAR(20),
    password_hash VARCHAR(255),                         -- NULL untuk user Google OAuth
    picture_url   TEXT,
    provider      VARCHAR(20)  NOT NULL DEFAULT 'local',
    provider_sub  VARCHAR(255),                         -- "sub" dari Google
    role          VARCHAR(10)  NOT NULL DEFAULT 'user',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at    TIMESTAMPTZ,
    CONSTRAINT users_role_chk     CHECK (role IN ('user', 'admin')),
    CONSTRAINT users_provider_chk CHECK (provider IN ('local', 'google')),
    CONSTRAINT users_password_chk CHECK (provider <> 'local' OR password_hash IS NOT NULL)
);
-- Email unik hanya di antara user aktif → user yang di-soft-delete bisa daftar ulang.
CREATE UNIQUE INDEX users_email_uq        ON users (lower(email))  WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX users_provider_sub_uq ON users (provider, provider_sub) WHERE provider_sub IS NOT NULL AND deleted_at IS NULL;
CREATE INDEX        users_deleted_at_idx  ON users (deleted_at);

-- Sama seperti "Alamat Saya" di Shopee.
CREATE TABLE user_addresses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label          VARCHAR(30),                         -- "Rumah", "Kantor"
    recipient_name VARCHAR(255) NOT NULL,
    phone          VARCHAR(20)  NOT NULL,
    province       VARCHAR(100) NOT NULL,
    city           VARCHAR(100) NOT NULL,
    district       VARCHAR(100) NOT NULL,               -- kecamatan
    postal_code    VARCHAR(10)  NOT NULL,
    address_line   TEXT         NOT NULL,               -- jalan, no. rumah, patokan
    is_default     BOOLEAN      NOT NULL DEFAULT false,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at     TIMESTAMPTZ
);
CREATE INDEX        user_addresses_user_idx    ON user_addresses (user_id) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX user_addresses_default_uq  ON user_addresses (user_id) WHERE is_default AND deleted_at IS NULL;

-- ---------------------------------------------------------------------
-- 2. MASTER DATA: brand, aroma, botol
--    Ini "bahan baku" internal. Yang dilihat customer adalah products
--    (listing) di bagian 3 — persis seperti di Shopee.
-- ---------------------------------------------------------------------
CREATE TABLE brands (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    slug        VARCHAR(255) NOT NULL,
    description TEXT,
    logo_url    TEXT,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ
);
CREATE UNIQUE INDEX brands_slug_uq ON brands (slug) WHERE deleted_at IS NULL;

-- Satu baris = satu aroma (mis. "Baccarat Rouge", inspired by MFK).
CREATE TABLE aromas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id     BIGINT       REFERENCES brands (id) ON DELETE RESTRICT,   -- brand inspirasi, boleh NULL
    name         VARCHAR(255) NOT NULL,
    slug         VARCHAR(255) NOT NULL,
    description  TEXT,
    gender       VARCHAR(10)  NOT NULL DEFAULT 'unisex',
    grade        VARCHAR(20)  NOT NULL DEFAULT 'regular',
    top_notes    TEXT,
    middle_notes TEXT,
    base_notes   TEXT,
    image_url    TEXT,
    is_active    BOOLEAN      NOT NULL DEFAULT true,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at   TIMESTAMPTZ,
    CONSTRAINT aromas_gender_chk CHECK (gender IN ('men', 'women', 'unisex')),
    CONSTRAINT aromas_grade_chk  CHECK (grade  IN ('regular', 'exclusive', 'super_exclusive'))
);
CREATE UNIQUE INDEX aromas_slug_uq   ON aromas (slug) WHERE deleted_at IS NULL;
CREATE INDEX        aromas_brand_idx ON aromas (brand_id);

-- Satu baris = satu model botol (mis. "Spray Kaca 30ml").
CREATE TABLE bottles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    slug        VARCHAR(255) NOT NULL,
    bottle_type VARCHAR(30)  NOT NULL,                  -- spray, roll_on, dll.
    volume_ml   INTEGER      NOT NULL,
    description TEXT,
    image_url   TEXT,
    is_active   BOOLEAN      NOT NULL DEFAULT true,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ,
    CONSTRAINT bottles_volume_chk CHECK (volume_ml > 0)
);
CREATE UNIQUE INDEX bottles_slug_uq ON bottles (slug) WHERE deleted_at IS NULL;

-- ---------------------------------------------------------------------
-- 3. KATALOG — meniru struktur listing Shopee 1:1
--
--    Shopee                     →  tabel ini
--    Item / Listing             →  products
--    Etalase toko               →  shop_categories (+ product_shop_categories)
--    Foto produk (maks 9)       →  product_images
--    Variasi 1 & 2 (nama tier)  →  product_variations   (tier_index 0 / 1)
--    Pilihan variasi            →  product_variation_options
--    Model (kombinasi = SKU)    →  product_models       (harga & stok di sini)
-- ---------------------------------------------------------------------
CREATE TABLE shop_categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    slug       VARCHAR(100) NOT NULL,
    sort_order INTEGER      NOT NULL DEFAULT 0,
    is_active  BOOLEAN      NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX shop_categories_slug_uq ON shop_categories (slug) WHERE deleted_at IS NULL;

CREATE TABLE products (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shopee_item_id BIGINT,                              -- item_id listing yang sama di Shopee
    name           VARCHAR(255) NOT NULL,               -- samakan dengan judul listing Shopee
    slug           VARCHAR(255) NOT NULL,
    description    TEXT         NOT NULL DEFAULT '',
    product_type   VARCHAR(20)  NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'draft',
    parent_sku     VARCHAR(100),                        -- "SKU Induk" di Shopee
    weight_gram    INTEGER      NOT NULL DEFAULT 0,     -- untuk ongkir
    sort_order     INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at     TIMESTAMPTZ,
    CONSTRAINT products_type_chk   CHECK (product_type IN ('perfume', 'empty_bottle', 'other')),
    CONSTRAINT products_status_chk CHECK (status IN ('draft', 'active', 'unlisted')),
    CONSTRAINT products_weight_chk CHECK (weight_gram >= 0)
);
CREATE UNIQUE INDEX products_slug_uq        ON products (slug)           WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX products_shopee_item_uq ON products (shopee_item_id) WHERE shopee_item_id IS NOT NULL AND deleted_at IS NULL;
CREATE INDEX        products_listing_idx    ON products (status, sort_order) WHERE deleted_at IS NULL;

CREATE TABLE product_shop_categories (
    product_id       BIGINT NOT NULL REFERENCES products (id)        ON DELETE CASCADE,
    shop_category_id BIGINT NOT NULL REFERENCES shop_categories (id) ON DELETE CASCADE,
    PRIMARY KEY (product_id, shop_category_id)
);
CREATE INDEX product_shop_categories_cat_idx ON product_shop_categories (shop_category_id);

CREATE TABLE product_images (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    url        TEXT        NOT NULL,
    sort_order SMALLINT    NOT NULL DEFAULT 0,         -- 0 = foto sampul
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT product_images_sort_uq UNIQUE (product_id, sort_order)
);

-- Nama tingkat variasi. Shopee: maks 2 tingkat → tier_index 0 atau 1.
CREATE TABLE product_variations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    tier_index SMALLINT    NOT NULL,
    name       VARCHAR(50) NOT NULL,                    -- "Aroma", "Ukuran"
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT product_variations_tier_chk CHECK (tier_index IN (0, 1)),
    CONSTRAINT product_variations_tier_uq  UNIQUE (product_id, tier_index)
);

-- Pilihan di tiap tingkat, urutan sama dengan di Shopee (option_index).
-- aroma_id / bottle_id menghubungkan pilihan ke master data (opsional).
CREATE TABLE product_variation_options (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variation_id BIGINT       NOT NULL REFERENCES product_variations (id) ON DELETE CASCADE,
    product_id   BIGINT       NOT NULL,                 -- denormalisasi untuk FK komposit di product_models
    option_index SMALLINT     NOT NULL,
    label        VARCHAR(100) NOT NULL,                 -- "Baccarat Rouge", "30ml Spray"
    image_url    TEXT,                                  -- Shopee: hanya tingkat 1 yang bergambar
    aroma_id     BIGINT       REFERENCES aromas (id)  ON DELETE RESTRICT,
    bottle_id    BIGINT       REFERENCES bottles (id) ON DELETE RESTRICT,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pvo_index_chk      CHECK (option_index >= 0),
    CONSTRAINT pvo_index_uq       UNIQUE (variation_id, option_index),
    CONSTRAINT pvo_label_uq       UNIQUE (variation_id, label),
    CONSTRAINT pvo_id_product_uq  UNIQUE (id, product_id),
    CONSTRAINT pvo_product_fk     FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE
);
CREATE INDEX pvo_aroma_idx  ON product_variation_options (aroma_id)  WHERE aroma_id  IS NOT NULL;
CREATE INDEX pvo_bottle_idx ON product_variation_options (bottle_id) WHERE bottle_id IS NOT NULL;

-- Model = kombinasi pilihan = 1 SKU yang bisa dibeli. Harga & stok di sini.
-- Produk tanpa variasi (mis. 1 jenis botol) tetap punya 1 model dengan option NULL.
CREATE TABLE product_models (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      BIGINT       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    option1_id      BIGINT,                             -- pilihan tingkat 1 (tier_index 0)
    option2_id      BIGINT,                             -- pilihan tingkat 2 (tier_index 1)
    shopee_model_id BIGINT,                             -- model_id yang sama di Shopee
    sku             VARCHAR(100),                       -- "SKU" variasi di Shopee
    price           BIGINT       NOT NULL,              -- harga jual (Rp)
    original_price  BIGINT,                             -- harga coret (Rp), NULL = tidak diskon
    stock           INTEGER      NOT NULL DEFAULT 0,
    weight_gram     INTEGER,                            -- NULL = pakai products.weight_gram
    is_active       BOOLEAN      NOT NULL DEFAULT true,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ,
    CONSTRAINT pm_price_chk          CHECK (price > 0),
    CONSTRAINT pm_original_price_chk CHECK (original_price IS NULL OR original_price >= price),
    CONSTRAINT pm_stock_chk          CHECK (stock >= 0),
    CONSTRAINT pm_option_order_chk   CHECK (option2_id IS NULL OR option1_id IS NOT NULL),
    -- FK komposit: pilihan WAJIB milik produk yang sama
    CONSTRAINT pm_option1_fk FOREIGN KEY (option1_id, product_id)
        REFERENCES product_variation_options (id, product_id),
    CONSTRAINT pm_option2_fk FOREIGN KEY (option2_id, product_id)
        REFERENCES product_variation_options (id, product_id)
);
-- Satu kombinasi hanya boleh muncul sekali per produk (NULL dianggap sama).
CREATE UNIQUE INDEX pm_combination_uq    ON product_models (product_id, COALESCE(option1_id, 0), COALESCE(option2_id, 0)) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX pm_sku_uq            ON product_models (sku)             WHERE sku IS NOT NULL AND deleted_at IS NULL;
CREATE UNIQUE INDEX pm_shopee_model_uq   ON product_models (shopee_model_id) WHERE shopee_model_id IS NOT NULL AND deleted_at IS NULL;
CREATE INDEX        pm_product_idx       ON product_models (product_id)      WHERE deleted_at IS NULL;
CREATE INDEX        pm_option2_idx       ON product_models (option2_id)      WHERE option2_id IS NOT NULL;

-- ---------------------------------------------------------------------
-- 4. KERANJANG — tanpa harga (harga selalu dibaca live dari product_models)
-- ---------------------------------------------------------------------
CREATE TABLE carts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX carts_user_uq ON carts (user_id) WHERE deleted_at IS NULL;

CREATE TABLE cart_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id          BIGINT      NOT NULL REFERENCES carts (id)          ON DELETE CASCADE,
    product_model_id BIGINT      NOT NULL REFERENCES product_models (id) ON DELETE CASCADE,
    quantity         INTEGER     NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT cart_items_qty_chk  CHECK (quantity > 0),
    CONSTRAINT cart_items_model_uq UNIQUE (cart_id, product_model_id)
);
CREATE INDEX cart_items_model_idx ON cart_items (product_model_id);

-- ---------------------------------------------------------------------
-- 5. ORDER
-- ---------------------------------------------------------------------
CREATE TABLE orders (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no           VARCHAR(32)  NOT NULL,           -- nomor pesanan untuk customer, mis. SP2611060001
    user_id            BIGINT       NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    status             VARCHAR(20)  NOT NULL DEFAULT 'PENDING_PAYMENT',

    subtotal           BIGINT       NOT NULL,           -- Σ order_items.subtotal
    shipping_fee       BIGINT       NOT NULL DEFAULT 0,
    discount           BIGINT       NOT NULL DEFAULT 0,
    total              BIGINT       NOT NULL,           -- yang ditagih ke Xendit
    total_quantity     INTEGER      NOT NULL,

    -- snapshot alamat (alamat user boleh berubah, order tidak)
    recipient_name     VARCHAR(255) NOT NULL,
    recipient_phone    VARCHAR(20)  NOT NULL,
    shipping_province  VARCHAR(100) NOT NULL,
    shipping_city      VARCHAR(100) NOT NULL,
    shipping_district  VARCHAR(100) NOT NULL,
    shipping_postal    VARCHAR(10)  NOT NULL,
    shipping_address   TEXT         NOT NULL,
    courier            VARCHAR(50),                     -- "JNE REG", "J&T EZ"
    tracking_number    VARCHAR(100),                    -- nomor resi
    buyer_note         TEXT,

    paid_at            TIMESTAMPTZ,
    shipped_at         TIMESTAMPTZ,
    completed_at       TIMESTAMPTZ,
    cancelled_at       TIMESTAMPTZ,
    cancel_reason      TEXT,

    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at         TIMESTAMPTZ,

    CONSTRAINT orders_status_chk CHECK (status IN (
        'PENDING_PAYMENT',   -- Shopee: Belum Bayar
        'PAID',              -- Shopee: Dikemas (sudah bayar, belum diproses)
        'PROCESSING',        -- Shopee: Dikemas
        'SHIPPED',           -- Shopee: Dikirim
        'COMPLETED',         -- Shopee: Selesai
        'CANCELLED',         -- Shopee: Dibatalkan
        'EXPIRED',           -- Shopee: Dibatalkan (otomatis, tidak dibayar)
        'REFUNDED'           -- Shopee: Pengembalian
    )),
    CONSTRAINT orders_amount_chk CHECK (
        subtotal >= 0 AND shipping_fee >= 0 AND discount >= 0
        AND total = subtotal + shipping_fee - discount
        AND total > 0
    ),
    CONSTRAINT orders_qty_chk     CHECK (total_quantity > 0),
    CONSTRAINT orders_paid_at_chk CHECK (status IN ('PENDING_PAYMENT', 'CANCELLED', 'EXPIRED') OR paid_at IS NOT NULL)
);
CREATE UNIQUE INDEX orders_order_no_uq       ON orders (order_no);
CREATE INDEX        orders_user_created_idx  ON orders (user_id, created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX        orders_status_created_idx ON orders (status, created_at DESC) WHERE deleted_at IS NULL;

-- Snapshot lengkap: kalau harga/nama/produk berubah atau dihapus, order tidak ikut berubah.
CREATE TABLE order_items (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id             BIGINT       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_model_id     BIGINT       REFERENCES product_models (id) ON DELETE SET NULL,  -- hanya referensi
    product_id           BIGINT       REFERENCES products (id)       ON DELETE SET NULL,
    -- snapshot ↓
    product_name         VARCHAR(255) NOT NULL,
    variation_name       VARCHAR(255),                  -- "Baccarat Rouge, 30ml Spray" (persis seperti di Shopee)
    option1_label        VARCHAR(100),
    option2_label        VARCHAR(100),
    sku                  VARCHAR(100),
    image_url            TEXT,
    unit_price           BIGINT       NOT NULL,         -- harga saat checkout
    original_unit_price  BIGINT,                        -- harga coret saat checkout
    quantity             INTEGER      NOT NULL,
    subtotal             BIGINT       NOT NULL,
    weight_gram          INTEGER      NOT NULL DEFAULT 0,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT order_items_price_chk    CHECK (unit_price > 0),
    CONSTRAINT order_items_qty_chk      CHECK (quantity > 0),
    CONSTRAINT order_items_subtotal_chk CHECK (subtotal = unit_price * quantity)
);
CREATE INDEX order_items_order_idx ON order_items (order_id);
CREATE INDEX order_items_model_idx ON order_items (product_model_id) WHERE product_model_id IS NOT NULL;

-- ---------------------------------------------------------------------
-- 6. PAYMENT — Xendit Payment Sessions (lihat docs/audit-and-roadmap.md §9)
-- ---------------------------------------------------------------------
CREATE TABLE payments (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                    BIGINT       NOT NULL REFERENCES orders (id) ON DELETE RESTRICT,
    provider                    VARCHAR(20)  NOT NULL DEFAULT 'xendit',
    reference_id                UUID         NOT NULL,      -- dikirim ke Xendit sebagai reference_id
    provider_session_id         VARCHAR(100),               -- payment_session_id ("ps-...")
    provider_payment_request_id VARCHAR(100),               -- payment_request_id
    provider_payment_id         VARCHAR(100),               -- payment_id (kunci dedup webhook)
    checkout_url                TEXT,                       -- payment_link_url
    payment_method              VARCHAR(50),                -- QRIS, VIRTUAL_ACCOUNT, EWALLET, ...
    payment_channel             VARCHAR(50),                -- BCA, OVO, DANA, ...
    amount                      BIGINT       NOT NULL,
    currency                    CHAR(3)      NOT NULL DEFAULT 'IDR',
    status                      VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    failure_reason              TEXT,
    expires_at                  TIMESTAMPTZ,
    paid_at                     TIMESTAMPTZ,
    provider_response           JSONB,                      -- respons create session terakhir
    created_at                  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at                  TIMESTAMPTZ,
    CONSTRAINT payments_provider_chk CHECK (provider IN ('xendit', 'midtrans')),
    CONSTRAINT payments_status_chk   CHECK (status IN ('PENDING', 'PAID', 'EXPIRED', 'CANCELLED', 'FAILED', 'REFUNDED')),
    CONSTRAINT payments_amount_chk   CHECK (amount > 0),
    CONSTRAINT payments_currency_chk CHECK (currency = 'IDR'),
    CONSTRAINT payments_paid_at_chk  CHECK (status NOT IN ('PAID', 'REFUNDED') OR paid_at IS NOT NULL)
);
CREATE UNIQUE INDEX payments_reference_uq        ON payments (reference_id);
CREATE UNIQUE INDEX payments_provider_session_uq ON payments (provider, provider_session_id) WHERE provider_session_id IS NOT NULL;
CREATE UNIQUE INDEX payments_provider_payment_uq ON payments (provider, provider_payment_id) WHERE provider_payment_id IS NOT NULL;
-- Maks 1 percobaan PENDING dan maks 1 PAID per order.
CREATE UNIQUE INDEX payments_one_pending_uq      ON payments (order_id) WHERE status = 'PENDING' AND deleted_at IS NULL;
CREATE UNIQUE INDEX payments_one_paid_uq         ON payments (order_id) WHERE status = 'PAID'    AND deleted_at IS NULL;
CREATE INDEX        payments_order_idx           ON payments (order_id);
-- Untuk job rekonsiliasi: cari PENDING yang sudah lewat expires_at.
CREATE INDEX        payments_pending_expiry_idx  ON payments (expires_at) WHERE status = 'PENDING';

-- Log webhook mentah, append-only (tanpa soft delete). Dedup via unique key.
CREATE TABLE payment_events (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider            VARCHAR(20)  NOT NULL,
    event_type          VARCHAR(100) NOT NULL,          -- payment_session.completed, ...
    provider_payment_id VARCHAR(100) NOT NULL,
    payment_id          BIGINT       REFERENCES payments (id) ON DELETE SET NULL,
    payload             JSONB        NOT NULL,
    received_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    processed_at        TIMESTAMPTZ,
    process_error       TEXT,
    CONSTRAINT payment_events_dedup_uq UNIQUE (provider, event_type, provider_payment_id)
);
CREATE INDEX payment_events_payment_idx     ON payment_events (payment_id);
CREATE INDEX payment_events_unprocessed_idx ON payment_events (received_at) WHERE processed_at IS NULL;

COMMIT;
