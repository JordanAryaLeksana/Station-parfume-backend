-- 1. USERS
-- ---------------------------------------------------------------------
-- role: user = pembeli; owner/admin/warehouse/cs = staf toko (peran tetap).
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    phone         VARCHAR(20),
    password_hash VARCHAR(255),                          -- NULL untuk user Google OAuth
    picture_url   TEXT,
    provider      VARCHAR(20)  NOT NULL DEFAULT 'local',
    provider_sub  VARCHAR(255),                          -- "sub" dari Google
    role          VARCHAR(10)  NOT NULL DEFAULT 'user',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at    TIMESTAMPTZ,
    CONSTRAINT users_role_chk     CHECK (role IN ('user', 'owner', 'admin', 'warehouse', 'cs')),
    CONSTRAINT users_provider_chk CHECK (provider IN ('local', 'google')),
    CONSTRAINT users_password_chk CHECK (provider <> 'local' OR password_hash IS NOT NULL)
);
-- Email unik hanya di antara user aktif → user yang di-soft-delete bisa daftar ulang.
CREATE UNIQUE INDEX users_email_uq        ON users (lower(email))  WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX users_provider_sub_uq ON users (provider, provider_sub) WHERE provider_sub IS NOT NULL AND deleted_at IS NULL;
CREATE INDEX        users_deleted_at_idx  ON users (deleted_at);
CREATE INDEX        users_staff_idx       ON users (role) WHERE role <> 'user' AND deleted_at IS NULL;

-- ---------------------------------------------------------------------
-- 2. KATALOG & STOK
--
--    products  = 1 halaman di website. kind:
--                perfume = 1 grup foto (mis. "Annasui"): punya scents
--                          (Dolly Girl, Sweet Dream), dijual per
--                          wangian × ukuran × murni/campur.
--                general = produk biasa (botol spray, souvenir, Al Rehab):
--                          varian cukup berupa label ("Pakai foto").
--    variants  = yang dibeli.
--
--    HARGA PARFUM (dihitung, tidak diketik per varian):
--      harga = tarif per ml wangian (murni = "bibit" / campur = "parfum")
--              × volume ukuran + harga botol ukuran
--      mis. Victoria 30 ml murni = 3.000 × 30 + 5.000 = Rp95.000.
--      variants.price (opsional) = harga khusus yang mengalahkan rumus.
--    HARGA PRODUK GENERAL: variants.price (wajib kalau aktif).
--
--    Ukuran: produk memakai sizes yang is_default (20/30/50 ml), kecuali
--    punya daftar sendiri di product_sizes (mis. 10/15/30 ml).
--
--    STOK: products.track_stock = false → selalu tersedia, tidak di-reserve
--    (parfum diracik sendiri). true → variants.stock & variants.reserved
--    (produk umum). Tersedia = stock − reserved; reserved = tertahan order
--    yang belum dibayar.
-- ---------------------------------------------------------------------
CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id  BIGINT       REFERENCES categories (id) ON DELETE RESTRICT,  -- sub-kategori (opsional)
    name       VARCHAR(100) NOT NULL,
    slug       VARCHAR(100) NOT NULL,
    sort_order INTEGER      NOT NULL DEFAULT 0,
    is_active  BOOLEAN      NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT categories_parent_chk CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE UNIQUE INDEX categories_slug_uq ON categories (slug) WHERE deleted_at IS NULL;

CREATE TABLE products (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id    BIGINT       NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
    kind           VARCHAR(10)  NOT NULL,
    code           VARCHAR(60)  NOT NULL,                -- kunci stabil untuk seed/impor: "annasui", "exclusive-3"
    name           VARCHAR(255) NOT NULL,                -- "Annasui", "Exclusive", "Botol spray"
    slug           VARCHAR(255) NOT NULL,
    description    TEXT         NOT NULL DEFAULT '',
    -- khusus parfum (dari foto produk)
    grade          VARCHAR(20),                          -- regular | exclusive
    inspired_by    VARCHAR(255),                         -- "Anna sui"
    note_primary   VARCHAR(20),                          -- label aroma pertama di foto
    note_secondary VARCHAR(20),
    -- umum
    weight_gram    INTEGER      NOT NULL DEFAULT 0,      -- berat default untuk produk general
    track_stock    BOOLEAN      NOT NULL DEFAULT true,   -- false = selalu tersedia (parfum diracik sendiri)
    status         VARCHAR(20)  NOT NULL DEFAULT 'draft',
    sort_order     INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at     TIMESTAMPTZ,
    CONSTRAINT products_kind_chk   CHECK (kind IN ('perfume', 'general')),
    CONSTRAINT products_status_chk CHECK (status IN ('draft', 'active', 'archived')),
    CONSTRAINT products_weight_chk CHECK (weight_gram >= 0),
    CONSTRAINT products_grade_chk  CHECK (grade IN ('regular', 'exclusive')),
    CONSTRAINT products_notes_chk  CHECK (
        note_primary   IN ('amber','aromatic','balsamic','citrus','creamy','floral','fresh','fruity','musk','oud','powdery','sweet','woody')
        AND note_secondary IN ('amber','aromatic','balsamic','citrus','creamy','floral','fresh','fruity','musk','oud','powdery','sweet','woody')
        AND note_primary <> note_secondary
    ),
    -- parfum wajib punya grade + 2 label aroma; produk general tidak boleh punya
    CONSTRAINT products_perfume_fields_chk CHECK (
        (kind = 'perfume' AND grade IS NOT NULL AND note_primary IS NOT NULL AND note_secondary IS NOT NULL)
        OR (kind = 'general' AND grade IS NULL AND inspired_by IS NULL AND note_primary IS NULL AND note_secondary IS NULL)
    )
);
CREATE UNIQUE INDEX products_code_uq      ON products (code) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX products_slug_uq      ON products (slug) WHERE deleted_at IS NULL;
CREATE INDEX        products_listing_idx  ON products (status, kind, grade, sort_order) WHERE deleted_at IS NULL;
CREATE INDEX        products_category_idx ON products (category_id, status) WHERE deleted_at IS NULL;

-- Varian wangian di dalam 1 produk parfum (bullet di foto).
CREATE TABLE scents (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    code       VARCHAR(100) NOT NULL,                    -- "annasui-dolly-girl"
    name       VARCHAR(100) NOT NULL,                    -- "Dolly Girl"
    price_per_ml_murni  BIGINT,                          -- tarif "bibit" (Rp/ml); NULL = belum ada tarif → tidak dijual
    price_per_ml_campur BIGINT,                          -- tarif "parfum" (Rp/ml)
    sort_order INTEGER      NOT NULL DEFAULT 0,
    is_active  BOOLEAN      NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT scents_id_product_uq UNIQUE (id, product_id),  -- untuk FK komposit di variants
    CONSTRAINT scents_rate_chk CHECK ((price_per_ml_murni IS NULL OR price_per_ml_murni > 0)
                                      AND (price_per_ml_campur IS NULL OR price_per_ml_campur > 0))
);
CREATE UNIQUE INDEX scents_code_uq         ON scents (code) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX scents_product_name_uq ON scents (product_id, lower(name)) WHERE deleted_at IS NULL;

CREATE TABLE product_images (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    scent_id   BIGINT      REFERENCES scents (id) ON DELETE CASCADE,   -- foto khusus 1 wangian (opsional)
    url        TEXT        NOT NULL,                     -- link CDN; file tidak disimpan di backend
    sort_order SMALLINT    NOT NULL DEFAULT 0,           -- 0 = foto sampul
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX product_images_product_idx ON product_images (product_id, sort_order);

-- Ukuran botol parfum. 1 ukuran = 1 jenis botol, jadi harga botol melekat di sini.
-- is_default = dijual untuk semua parfum (20/30/50 ml); ukuran lain (10/15 ml)
-- hanya untuk produk yang mencantumkannya di product_sizes.
CREATE TABLE sizes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label        VARCHAR(20)  NOT NULL,                  -- "30 ml"
    volume_ml    INTEGER      NOT NULL,
    bottle_price BIGINT       NOT NULL DEFAULT 0,        -- harga botol (Rp), ditambahkan ke harga parfum
    weight_gram  INTEGER      NOT NULL DEFAULT 0,        -- berat kirim (botol + isi + kemasan)
    is_default   BOOLEAN      NOT NULL DEFAULT false,
    sort_order   INTEGER      NOT NULL DEFAULT 0,
    is_active    BOOLEAN      NOT NULL DEFAULT true,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT sizes_volume_chk CHECK (volume_ml > 0),
    CONSTRAINT sizes_amount_chk CHECK (bottle_price >= 0 AND weight_gram >= 0),
    CONSTRAINT sizes_volume_uq  UNIQUE (volume_ml)
);

-- Ukuran khusus per produk parfum. Produk tanpa baris di sini memakai semua
-- sizes.is_default; produk dengan baris di sini HANYA memakai ukuran ini.
CREATE TABLE product_sizes (
    product_id BIGINT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    size_id    BIGINT NOT NULL REFERENCES sizes (id)    ON DELETE RESTRICT,
    PRIMARY KEY (product_id, size_id)
);

-- Yang dibeli pembeli. Parfum: scent + size + concentration wajib diisi.
-- Produk general: ketiganya NULL, boleh punya label ("Pakai foto").
-- price: parfum = harga khusus opsional (NULL = pakai rumus tarif × ml + botol);
--        general = harga jual (wajib kalau aktif).
-- stock/reserved: hanya dipakai kalau products.track_stock = true.
CREATE TABLE variants (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       BIGINT       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    scent_id         BIGINT,
    size_id          BIGINT       REFERENCES sizes (id) ON DELETE RESTRICT,
    concentration    VARCHAR(10),                        -- murni | campur
    label            VARCHAR(100),                       -- produk general: "Pakai foto", "Lemon"
    code             VARCHAR(120) NOT NULL,              -- kode otomatis: "annasui-dolly-girl-30-murni"
    price            BIGINT,                             -- harga khusus/tetap (Rp), lihat komentar di atas
    compare_at_price BIGINT,                             -- harga coret (Rp)
    weight_gram      INTEGER,                            -- NULL = dari sizes / products
    stock            INTEGER      NOT NULL DEFAULT 0,    -- stok fisik di toko
    reserved         INTEGER      NOT NULL DEFAULT 0,    -- tertahan order belum bayar
    is_active        BOOLEAN      NOT NULL DEFAULT false,
    sort_order       INTEGER      NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at       TIMESTAMPTZ,
    CONSTRAINT variants_concentration_chk CHECK (concentration IN ('murni', 'campur')),
    CONSTRAINT variants_shape_chk CHECK (
        (scent_id IS NOT NULL AND size_id IS NOT NULL AND concentration IS NOT NULL)
        OR (scent_id IS NULL AND size_id IS NULL AND concentration IS NULL)
    ),
    CONSTRAINT variants_price_chk         CHECK (price IS NULL OR price > 0),
    CONSTRAINT variants_active_price_chk  CHECK (scent_id IS NOT NULL OR NOT is_active OR price IS NOT NULL),
    CONSTRAINT variants_compare_price_chk CHECK (compare_at_price IS NULL OR price IS NULL OR compare_at_price > price),
    CONSTRAINT variants_weight_chk        CHECK (weight_gram IS NULL OR weight_gram >= 0),
    CONSTRAINT variants_stock_chk         CHECK (stock >= 0 AND reserved >= 0),
    -- FK komposit: wangian WAJIB milik produk yang sama
    CONSTRAINT variants_scent_fk FOREIGN KEY (scent_id, product_id) REFERENCES scents (id, product_id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX variants_combination_uq ON variants (product_id, COALESCE(scent_id, 0), COALESCE(size_id, 0),
                                                         COALESCE(concentration, ''), COALESCE(lower(label), ''))
    WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX variants_code_uq     ON variants (code) WHERE deleted_at IS NULL;
CREATE INDEX        variants_product_idx ON variants (product_id, sort_order) WHERE deleted_at IS NULL;
CREATE INDEX        variants_scent_idx   ON variants (scent_id) WHERE scent_id IS NOT NULL;

-- ---------------------------------------------------------------------
-- 3. KERANJANG — tanpa harga (harga selalu dihitung live)
-- ---------------------------------------------------------------------
CREATE TABLE carts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX carts_user_uq ON carts (user_id) WHERE deleted_at IS NULL;

CREATE TABLE cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id    BIGINT      NOT NULL REFERENCES carts (id)    ON DELETE CASCADE,
    variant_id BIGINT      NOT NULL REFERENCES variants (id) ON DELETE CASCADE,
    quantity   INTEGER     NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT cart_items_qty_chk    CHECK (quantity > 0),
    CONSTRAINT cart_items_variant_uq UNIQUE (cart_id, variant_id)
);
CREATE INDEX cart_items_variant_idx ON cart_items (variant_id);

-- ---------------------------------------------------------------------
-- 4. ORDER — ongkir ditanggung toko (shipping_fee = 0). Dikirim manual
--    dari toko: admin cukup mengubah status ke SHIPPED (shipped_at terisi).
-- ---------------------------------------------------------------------
CREATE TABLE orders (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no          VARCHAR(32)  NOT NULL,             -- nomor pesanan untuk pembeli, mis. SP2611090A1B2C3D
    user_id           BIGINT       NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    status            VARCHAR(20)  NOT NULL DEFAULT 'PENDING_PAYMENT',

    subtotal          BIGINT       NOT NULL,             -- Σ order_items.subtotal
    shipping_fee      BIGINT       NOT NULL DEFAULT 0,
    total             BIGINT       NOT NULL,             -- yang ditagih lewat Xendit
    total_quantity    INTEGER      NOT NULL,

    -- snapshot alamat (diketik pembeli saat checkout)
    recipient_name    VARCHAR(255) NOT NULL,
    recipient_phone   VARCHAR(20)  NOT NULL,
    shipping_province VARCHAR(100) NOT NULL,
    shipping_city     VARCHAR(100) NOT NULL,
    shipping_district VARCHAR(100) NOT NULL,
    shipping_postal   VARCHAR(10)  NOT NULL,
    shipping_address  TEXT         NOT NULL,
    buyer_note        TEXT,

    paid_at           TIMESTAMPTZ,
    shipped_at        TIMESTAMPTZ,
    completed_at      TIMESTAMPTZ,
    cancelled_at      TIMESTAMPTZ,
    cancel_reason     TEXT,
    expires_at        TIMESTAMPTZ,                       -- batas bayar; lewat = EXPIRED (reservasi stok dilepas)

    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at        TIMESTAMPTZ,

    CONSTRAINT orders_status_chk CHECK (status IN (
        'PENDING_PAYMENT',   -- Belum Bayar (stok di-reserve)
        'PAID',              -- Sudah bayar (stok terpotong)
        'PROCESSING',        -- Dikemas
        'SHIPPED',           -- Dikirim
        'COMPLETED',         -- Selesai
        'CANCELLED',         -- Dibatalkan
        'EXPIRED',           -- Dibatalkan otomatis (tidak dibayar)
        'REFUNDED'           -- Dana dikembalikan
    )),
    CONSTRAINT orders_amount_chk CHECK (
        subtotal >= 0 AND shipping_fee >= 0
        AND total = subtotal + shipping_fee
        AND total > 0
    ),
    CONSTRAINT orders_qty_chk     CHECK (total_quantity > 0),
    CONSTRAINT orders_paid_at_chk CHECK (status IN ('PENDING_PAYMENT', 'CANCELLED', 'EXPIRED') OR paid_at IS NOT NULL)
);
CREATE UNIQUE INDEX orders_order_no_uq        ON orders (order_no);
CREATE INDEX        orders_user_created_idx   ON orders (user_id, created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX        orders_status_created_idx ON orders (status, created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX        orders_pending_expiry_idx ON orders (expires_at) WHERE status = 'PENDING_PAYMENT';

-- Snapshot lengkap: kalau harga/nama/varian berubah atau dihapus, order tidak ikut berubah.
CREATE TABLE order_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    variant_id    BIGINT       REFERENCES variants (id) ON DELETE SET NULL,  -- referensi saja
    product_id    BIGINT       REFERENCES products (id) ON DELETE SET NULL,
    -- snapshot ↓
    product_name  VARCHAR(255) NOT NULL,                 -- "Annasui"
    grade         VARCHAR(20),                           -- regular | exclusive
    scent_name    VARCHAR(100),                          -- "Dolly Girl"
    size_label    VARCHAR(20),                           -- "30 ml"
    volume_ml     INTEGER,
    concentration VARCHAR(10),                           -- murni | campur
    variant_label VARCHAR(100),                          -- produk general
    variant_name  VARCHAR(255),                          -- teks tampilan: "Dolly Girl, 30 ml, Murni"
    variant_code  VARCHAR(120) NOT NULL,
    image_url     TEXT,
    unit_price    BIGINT       NOT NULL,                 -- harga per unit saat checkout
    price_per_ml  BIGINT,                                -- snapshot tarif (parfum; NULL = harga khusus/general)
    bottle_price  BIGINT,                                -- snapshot harga botol
    quantity      INTEGER      NOT NULL,
    subtotal      BIGINT       NOT NULL,
    weight_gram   INTEGER      NOT NULL DEFAULT 0,
    track_stock   BOOLEAN      NOT NULL DEFAULT true,    -- snapshot: stok di-reserve saat checkout?
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT order_items_price_chk    CHECK (unit_price > 0),
    CONSTRAINT order_items_qty_chk      CHECK (quantity > 0),
    CONSTRAINT order_items_subtotal_chk CHECK (subtotal = unit_price * quantity)
);
CREATE INDEX order_items_order_idx   ON order_items (order_id);
CREATE INDEX order_items_variant_idx ON order_items (variant_id) WHERE variant_id IS NOT NULL;

-- ---------------------------------------------------------------------
-- 5. RIWAYAT STOK — setiap perubahan variants.stock (append-only).
--    delta + = masuk, − = keluar.
-- ---------------------------------------------------------------------
CREATE TABLE stock_movements (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id  BIGINT      NOT NULL REFERENCES variants (id) ON DELETE CASCADE,
    delta       INTEGER     NOT NULL,
    stock_after INTEGER     NOT NULL,
    reason      VARCHAR(20) NOT NULL,
    order_id    BIGINT      REFERENCES orders (id) ON DELETE SET NULL,  -- penjualan
    user_id     BIGINT      REFERENCES users (id)  ON DELETE SET NULL,  -- admin yang mengubah
    note        TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT stock_movements_delta_chk  CHECK (delta <> 0),
    CONSTRAINT stock_movements_reason_chk CHECK (reason IN ('initial', 'restock', 'sale', 'return', 'adjustment', 'opname'))
);
CREATE INDEX stock_movements_variant_idx ON stock_movements (variant_id, created_at DESC);
CREATE INDEX stock_movements_order_idx   ON stock_movements (order_id) WHERE order_id IS NOT NULL;

-- ---------------------------------------------------------------------
-- 6. PAYMENT — Xendit Payment Sessions
-- ---------------------------------------------------------------------
CREATE TABLE payments (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                    BIGINT       NOT NULL REFERENCES orders (id) ON DELETE RESTRICT,
    provider                    VARCHAR(20)  NOT NULL DEFAULT 'xendit',
    reference_id                UUID         NOT NULL,      -- dikirim ke Xendit sebagai reference_id
    provider_session_id         VARCHAR(100),               -- payment_session_id ("ps-...")
    provider_payment_request_id VARCHAR(100),               -- payment_request_id
    provider_payment_id         VARCHAR(100),               -- payment_id (kunci dedup webhook)
    checkout_url                TEXT,                       -- payment_link_url
    payment_method              VARCHAR(50),                -- QRIS, VIRTUAL_ACCOUNT, EWALLET, ...
    payment_channel             VARCHAR(50),                -- BCA, OVO, DANA, ...
    amount                      BIGINT       NOT NULL,
    currency                    CHAR(3)      NOT NULL DEFAULT 'IDR',
    status                      VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    failure_reason              TEXT,                       -- alasan gagal/batal (mis. nominal beda, bayar ganda → refund manual)
    expires_at                  TIMESTAMPTZ,
    paid_at                     TIMESTAMPTZ,
    provider_response           JSONB,                      -- respons create session terakhir
    created_at                  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at                  TIMESTAMPTZ,
    CONSTRAINT payments_provider_chk CHECK (provider IN ('xendit')),
    CONSTRAINT payments_status_chk   CHECK (status IN ('PENDING', 'PAID', 'EXPIRED', 'CANCELLED', 'FAILED', 'REFUNDED')),
    CONSTRAINT payments_amount_chk   CHECK (amount > 0),
    CONSTRAINT payments_currency_chk CHECK (currency = 'IDR'),
    CONSTRAINT payments_paid_at_chk  CHECK (status NOT IN ('PAID', 'REFUNDED') OR paid_at IS NOT NULL)
);
CREATE UNIQUE INDEX payments_reference_uq        ON payments (reference_id);
CREATE UNIQUE INDEX payments_provider_session_uq ON payments (provider, provider_session_id) WHERE provider_session_id IS NOT NULL;
CREATE UNIQUE INDEX payments_provider_payment_uq ON payments (provider, provider_payment_id) WHERE provider_payment_id IS NOT NULL;
-- Maks 1 percobaan PENDING dan maks 1 PAID per order.
CREATE UNIQUE INDEX payments_one_pending_uq      ON payments (order_id) WHERE status = 'PENDING' AND deleted_at IS NULL;
CREATE UNIQUE INDEX payments_one_paid_uq         ON payments (order_id) WHERE status = 'PAID'    AND deleted_at IS NULL;
CREATE INDEX        payments_order_idx           ON payments (order_id);
-- Untuk job rekonsiliasi: cari PENDING yang sudah lewat expires_at.
CREATE INDEX        payments_pending_expiry_idx  ON payments (expires_at) WHERE status = 'PENDING';

-- Log webhook mentah, append-only (tanpa soft delete). Dedup via unique key.
CREATE TABLE payment_events (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider            VARCHAR(20)  NOT NULL,
    event_type          VARCHAR(100) NOT NULL,          -- payment_session.completed, ...
    provider_payment_id VARCHAR(100) NOT NULL,
    payment_id          BIGINT       REFERENCES payments (id) ON DELETE SET NULL,
    payload             JSONB        NOT NULL,
    received_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    processed_at        TIMESTAMPTZ,
    process_error       TEXT,
    CONSTRAINT payment_events_dedup_uq UNIQUE (provider, event_type, provider_payment_id)
);
CREATE INDEX payment_events_payment_idx     ON payment_events (payment_id);
CREATE INDEX payment_events_unprocessed_idx ON payment_events (received_at) WHERE processed_at IS NULL;

